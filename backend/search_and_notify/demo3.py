# ---------- 1. Что правила вытащили из текста
items = []
print(f"{line}\nРазметка (без LLM)\n{line}")
for f in FIXTURES:
    authority = "Правительство Москвы" if f["block"] == "subjects" else ""
    c = classify(f["name"], f["text"], PUB, authority, f["block"])
    if not c.relevant:
        print(f"{f['eo']}: пропущен — {c.reason}")
        continue
    a = c.audience
    print(f"{f['eo']}: формы={set(a.legal_forms or [])} режимы={set(a.tax_regimes or [])} "
          f"искл.режимы={set(a.exclude_tax_regimes or [])} ОКВЭД={a.okved_prefixes}{' (только основной)' if a.okved_main_only else ''} "
          f"регион={set(a.regions or [])} сотрудники={a.has_employees} признаки={a.any_flags} "
          f"| с {[d.strftime('%d.%m.%Y') for d in c.effective]} | узость={c.specificity} "
          f"| {'авто' if c.auto_publish else 'модерация'}")
    items.append(to_feed_item({"eoNumber": f["eo"], "name": f["name"], "complexName": f["name"]}, c, PUB, f["text"]))

# ---------- 2. Сведение с профилем МОСТАР (ЮЛ, Москва, ОКВЭД 74.10 + 62.09, УСН, сотрудники; про кассу не спрашивали)
p = Profile(inn=EGRUL["inn"], is_legal_entity=True, region_code="77", okved_main="74.10", okved_additional=("62.09",),
            msp_category=1, tax_regime="usn_income", has_employees=True, hints=profile_hints(EGRUL),
            flags={"works_with_selfemployed": True, "marketplace_seller": False})
print(f"\n{line}\nСведение с профилем МОСТАР\n{line}")
for it in items:
    m = match(p, it.audience)
    print(f"{it.id}: {m.level:<8} {'; '.join(m.reasons)}{('  ❓ ' + ', '.join(m.unknown)) if m.unknown else ''}")

company = company_ctx(EGRUL, MSP, EGRUL["inn"])
for d in run_feed(items, p, TODAY):
    ctx = build_context(d.type, d.payload, company, TODAY)
    if d.type == "law.upcoming":
        print(f"\n{line}\n▶ {d.type}  {d.key}\n{line}\n" + render(d.type, ctx))
    elif d.type == "profile.question":
        print(f"\n{line}\n▶ {d.type}  {d.key}\n{line}\n" + question_body(render(d.type, ctx), d.payload["flag"])["text"])
    else:
        print(f"\n▶ {d.type} (в сводку): {d.payload['title']}")
